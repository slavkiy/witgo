func (r *renderer) renderHostImportList(imports []worldInterface, importsVariable string) {
	fmt.Fprintln(&r.out, "\tvar _witgoImports []witgo.HostImport")
	for _, imported := range imports {
		host := importsVariable + "." + goName(imported.name)
		fmt.Fprintf(&r.out, "\tif %s != nil {\n", host)
		fmt.Fprintf(&r.out, "\t\tif _witgoSource, ok := %s.(interface{ witgoCompositionPlug() (witgo.CompositionPlug, bool) }); ok {\n", host)
		fmt.Fprintln(&r.out, "\t\t\t_witgoPlug, available := _witgoSource.witgoCompositionPlug()")
		fmt.Fprintln(&r.out, "\t\t\tif !available { return nil, witgo.ErrPluginProviderClosed }")
		fmt.Fprintf(&r.out, "\t\t\tif _witgoPlug.Interface != %s { return nil, fmt.Errorf(\"%%w: expected interface %%q, provider exposes %%q\", witgo.ErrPluginDependencyMismatch, %s, _witgoPlug.Interface) }\n", strconv.Quote(imported.callName), strconv.Quote(imported.callName))
		fmt.Fprintln(&r.out, "\t\t\t_witgoOptions.CompositionPlugs = append(_witgoOptions.CompositionPlugs, _witgoPlug)")
		fmt.Fprintln(&r.out, "\t\t} else {")
		for _, fn := range imported.functions {
			fmt.Fprintln(&r.out, "\t\t_witgoImports = append(_witgoImports, witgo.HostImport{")
			fmt.Fprintf(&r.out, "\t\t\tInterface: %s, Function: %s,\n", strconv.Quote(imported.callName), strconv.Quote(fn.Name))
			fmt.Fprintln(&r.out, "\t\t\tCallContext: func(ctx context.Context, _witgoArgs []any) (any, error) {")
			fmt.Fprintf(&r.out, "\t\t\t\tif len(_witgoArgs) != %d { return nil, fmt.Errorf(%q, len(_witgoArgs)) }\n", len(fn.Params), "host import "+imported.callName+"#"+fn.Name+" received %d arguments")
			args := make([]string, 0, len(fn.Params))
			for index, param := range fn.Params {
				name := fmt.Sprintf("_witgoArg%d", index)
				fmt.Fprintf(&r.out, "\t\t\t\t%s, err := %s\n", name, r.liftRuntimeExpr("nil", fmt.Sprintf("_witgoArgs[%d]", index), param.Type))
				fmt.Fprintln(&r.out, "\t\t\t\tif err != nil { return nil, err }")
				args = append(args, name)
			}
			callArgs := append([]string{"ctx"}, args...)
			call := host + "." + goName(fn.Name) + "(" + strings.Join(callArgs, ", ") + ")"
			if _, _, mapped := r.resultErrorParts(fn); mapped {
				r.renderResultErrorProvider("\t\t\t\t", call, fn)
			} else if fn.Result == nil {
				fmt.Fprintf(&r.out, "\t\t\t\treturn nil, %s\n", call)
			} else if conversion, ok := r.conversionName(fn.Result); ok {
				fmt.Fprintf(&r.out, "\t\t\t\t_witgoResult, err := %s\n", call)
				fmt.Fprintln(&r.out, "\t\t\t\tif err != nil { return nil, err }")
				fmt.Fprintf(&r.out, "\t\t\t\treturn lower%s(_witgoResult), nil\n", conversion)
			} else {
				fmt.Fprintf(&r.out, "\t\t\t\treturn %s\n", call)
			}
			fmt.Fprintln(&r.out, "\t\t\t},")
			fmt.Fprintln(&r.out, "\t\t})")
		}
		fmt.Fprintln(&r.out, "\t\t}")
		fmt.Fprintln(&r.out, "\t}")
	}
}

func (r *renderer) renderResultErrorProvider(indent, call string, fn *ir.Func) {
	okType, errType, _ := r.resultErrorParts(fn)
	r.needsErrors = true
	if isUnitType(okType) {
		fmt.Fprintf(&r.out, "%s_witgoErr := %s\n", indent, call)
	} else {
		fmt.Fprintf(&r.out, "%s_witgoOK, _witgoErr := %s\n", indent, call)
	}
	fmt.Fprintf(&r.out, "%sif _witgoErr != nil {\n", indent)
	fmt.Fprintf(&r.out, "%s\tvar _witgoWITErr witgo.WITError[%s]\n", indent, r.goType(errType))
	fmt.Fprintf(&r.out, "%s\tif errors.As(_witgoErr, &_witgoWITErr) { return witgo.Err[%s](_witgoWITErr.Value), nil }\n", indent, r.goType(okType))
	fmt.Fprintf(&r.out, "%s\treturn nil, _witgoErr\n%s}\n", indent, indent)
	if isUnitType(okType) {
		fmt.Fprintf(&r.out, "%sreturn witgo.Ok[witgo.Unit, %s](witgo.UnitValue()), nil\n", indent, r.goType(errType))
	} else {
		fmt.Fprintf(&r.out, "%sreturn witgo.Ok[%s, %s](_witgoOK), nil\n", indent, r.goType(okType), r.goType(errType))
	}
}

