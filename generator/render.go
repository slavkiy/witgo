func (r *renderer) resultErrorParts(fn *ir.Func) (ir.Type, ir.Type, bool) {
	if r.goOverlay == nil {
		return nil, nil, false
	}
	found := false
	for _, mapping := range r.goOverlay.errors {
		if mapping.Function == fn {
			found = true
			break
		}
	}
	if !found {
		return nil, nil, false
	}
	result, ok := fn.Result.(*ir.GenericType)
	if !ok || result.Name != "result" {
		return nil, nil, false
	}
	okType := ir.Type(&ir.NamedType{Wildcard: true})
	errType := ir.Type(&ir.NamedType{Wildcard: true})
	if len(result.Args) > 0 {
		okType = result.Args[0]
	}
	if len(result.Args) > 1 {
		errType = result.Args[1]
	}
	return okType, errType, true
}

func isUnitType(typ ir.Type) bool {
	named, ok := typ.(*ir.NamedType)
	return ok && named.Wildcard
}

func (r *renderer) contextParams(params []ir.Param) string {
	rest := r.params(params)
	if rest == "" {
		return "ctx context.Context"
	}
	return "ctx context.Context, " + rest
}

func (r *renderer) params(params []ir.Param) string {
	out := make([]string, 0, len(params))
	for index, param := range params {
		out = append(out, paramName(param, index)+" "+r.goType(param.Type))
	}
	return strings.Join(out, ", ")
}

func paramName(param ir.Param, index int) string {
	if param.Name == "" || param.Name == "self" {
		return fmt.Sprintf("arg%d", index)
	}
	return goLocalName(param.Name)
}

func modelMethodName(recordName, functionName string) string {
	method := goName(functionName)
	record := goName(recordName)
	if strings.HasSuffix(method, record) && len(method) > len(record) {
		return strings.TrimSuffix(method, record)
	}
	return method
}

func (r *renderer) goType(typ ir.Type) string {
	switch typ := typ.(type) {
	case nil:
		return "any"
	case *ir.PrimitiveType:
		if mapped, ok := primitiveType(typ.Name); ok {
			if typ.Name == "char" {
				r.needsWitgo = true
			}
			return mapped
		}
		return "any"
	case *ir.NamedType:
		if typ.Wildcard {
			r.needsWitgo = true
			return "witgo.Unit"
		}
		if typ.Name == "error-context" {
			return "witgo.Handle"
		}
		if mapped, ok := primitiveType(typ.Name); ok {
			if typ.Name == "char" {
				r.needsWitgo = true
			}
			return mapped
		}
		return goName(typ.Name)
	case *ir.GenericType:
		switch typ.Name {
		case "list":
			return "[]" + r.goType(firstType(typ.Args))
		case "option":
			r.needsWitgo = true
			return "witgo.Option[" + r.goType(firstType(typ.Args)) + "]"
		case "borrow", "own", "future", "stream":
			return "witgo.Handle"
		case "map":
			if len(typ.Args) == 2 {
				r.needsWitgo = true
				return "witgo.Map[" + r.goType(typ.Args[0]) + ", " + r.goType(typ.Args[1]) + "]"
			}
		case "result":
			r.needsWitgo = true
			if len(typ.Args) == 2 {
				return "witgo.Result[" + r.goType(typ.Args[0]) + ", " + r.goType(typ.Args[1]) + "]"
			}
			if len(typ.Args) == 1 {
				return "witgo.Result[" + r.goType(typ.Args[0]) + ", witgo.Unit]"
			}
			return "witgo.Result[witgo.Unit, witgo.Unit]"
		}
		args := make([]string, 0, len(typ.Args))
		for _, arg := range typ.Args {
			args = append(args, r.goType(arg))
		}
		return goName(typ.Name) + "[" + strings.Join(args, ", ") + "]"
	case *ir.TupleType:
		r.needsWitgo = true
		if len(typ.Items) > 16 {
			return "witgo.Tuple"
		}
		if len(typ.Items) == 0 {
			return "witgo.Tuple0"
		}
		args := make([]string, 0, len(typ.Items))
		for _, item := range typ.Items {
			args = append(args, r.goType(item))
		}
		return fmt.Sprintf("witgo.Tuple%d[%s]", len(args), strings.Join(args, ", "))
	default:
		return "any"
	}
}

func (r *renderer) typeMapping(name string) (resolvedTypeMapping, bool) {
	if r.goOverlay == nil {
		return resolvedTypeMapping{}, false
	}
	mapping, ok := r.goOverlay.types[name]
	return mapping, ok
}

func (r *renderer) recordHasOverlay(record *ir.Record) bool {
	for _, field := range record.Fields {
		if r.typeHasOverlay(field.Type, make(map[string]bool)) {
			return true
		}
	}
	return false
}

func (r *renderer) typeHasOverlay(typ ir.Type, seen map[string]bool) bool {
	switch typ := typ.(type) {
	case *ir.NamedType:
		if _, ok := r.typeMapping(typ.Name); ok {
			return true
		}
		if seen[typ.Name] {
			return false
		}
		seen[typ.Name] = true
		switch decl := r.namedTypes[typ.Name].(type) {
		case *ir.TypeDef:
			return r.typeHasOverlay(decl.Type, seen)
		case *ir.Record:
			return r.recordHasOverlay(decl)
		}
	case *ir.GenericType:
		for _, arg := range typ.Args {
			if r.typeHasOverlay(arg, seen) {
				return true
			}
		}
	case *ir.TupleType:
		for _, item := range typ.Items {
			if r.typeHasOverlay(item, seen) {
				return true
			}
		}
	}
	return false
}

func (r *renderer) wireGoType(typ ir.Type) string {
	switch typ := typ.(type) {
	case *ir.NamedType:
		if mapping, ok := r.typeMapping(typ.Name); ok {
			return r.wireGoType(mapping.Wire)
		}
		if record, ok := r.namedTypes[typ.Name].(*ir.Record); ok && r.recordHasOverlay(record) {
			return goLocalName(typ.Name) + "Wire"
		}
		return r.goType(typ)
	case *ir.GenericType, *ir.TupleType:
		return r.goType(typ)
	default:
		return r.goType(typ)
	}
}

func (r *renderer) renderMappedAliasCodec(decl *ir.TypeDef, mapping resolvedTypeMapping) {
	name := goName(decl.Name)
	wire := r.wireGoType(decl.Type)
	fmt.Fprintf(&r.out, "func lower%s(value %s) %s {\n", name, mapping.Config.GoType, wire)
	switch mapping.Config.Codec {
	case "unix-seconds":
		fmt.Fprintln(&r.out, "\treturn value.Unix()")
	case "unix-milliseconds":
		fmt.Fprintln(&r.out, "\treturn value.UnixMilli()")
	case "unix-nanoseconds":
		fmt.Fprintln(&r.out, "\treturn value.UnixNano()")
	case "duration-nanoseconds":
		fmt.Fprintf(&r.out, "\treturn %s(value)\n", wire)
	}
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintf(&r.out, "func lift%s(value %s) %s {\n", name, wire, mapping.Config.GoType)
	switch mapping.Config.Codec {
	case "unix-seconds":
		fmt.Fprintln(&r.out, "\treturn time.Unix(value, 0)")
	case "unix-milliseconds":
		fmt.Fprintln(&r.out, "\treturn time.UnixMilli(value)")
	case "unix-nanoseconds":
		fmt.Fprintln(&r.out, "\treturn time.Unix(0, value)")
	case "duration-nanoseconds":
		fmt.Fprintln(&r.out, "\treturn time.Duration(value)")
	}
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintf(&r.out, "func liftRuntime%s(value any) (%s, error) {\n", name, mapping.Config.GoType)
	fmt.Fprintf(&r.out, "\twire, err := liftValue[%s](value)\n", wire)
	fmt.Fprintln(&r.out, "\tif err != nil { var zero "+mapping.Config.GoType+"; return zero, err }")
	fmt.Fprintf(&r.out, "\treturn lift%s(wire), nil\n", name)
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
}

func (r *renderer) conversionName(typ ir.Type) (string, bool) {
	named, ok := typ.(*ir.NamedType)
	if !ok {
		return "", false
	}
	if _, ok := r.typeMapping(named.Name); ok {
		return goName(named.Name), true
	}
	if record, ok := r.namedTypes[named.Name].(*ir.Record); ok && r.recordHasOverlay(record) {
		return goName(named.Name), true
	}
	return "", false
}

func (r *renderer) renderRecordCodec(record *ir.Record) {
	publicName := goName(record.Name)
	wireName := goLocalName(record.Name) + "Wire"
	fmt.Fprintf(&r.out, "type %s struct {\n", wireName)
	for _, field := range record.Fields {
		fmt.Fprintf(&r.out, "\t%s %s `json:%s`\n", goName(field.Name), r.wireGoType(field.Type), strconv.Quote(field.Name))
	}
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintf(&r.out, "func lower%s(value %s) %s {\n", publicName, publicName, wireName)
	fmt.Fprintf(&r.out, "\tvar wire %s\n", wireName)
	for _, field := range record.Fields {
		fieldName := goName(field.Name)
		if conversion, ok := r.conversionName(field.Type); ok {
			fmt.Fprintf(&r.out, "\twire.%s = lower%s(value.%s)\n", fieldName, conversion, fieldName)
		} else {
			fmt.Fprintf(&r.out, "\twire.%s = value.%s\n", fieldName, fieldName)
		}
	}
	fmt.Fprintln(&r.out, "\treturn wire\n}")
	fmt.Fprintf(&r.out, "func lift%s(wire %s) %s {\n", publicName, wireName, publicName)
	fmt.Fprintf(&r.out, "\tvar value %s\n", publicName)
	for _, field := range record.Fields {
		fieldName := goName(field.Name)
		if conversion, ok := r.conversionName(field.Type); ok {
			fmt.Fprintf(&r.out, "\tvalue.%s = lift%s(wire.%s)\n", fieldName, conversion, fieldName)
		} else {
			fmt.Fprintf(&r.out, "\tvalue.%s = wire.%s\n", fieldName, fieldName)
		}
	}
	fmt.Fprintln(&r.out, "\treturn value\n}")
	fmt.Fprintf(&r.out, "func liftRuntime%s(raw any) (%s, error) {\n", publicName, publicName)
	fmt.Fprintf(&r.out, "\twire, err := liftValue[%s](raw)\n", wireName)
	fmt.Fprintf(&r.out, "\tif err != nil { var zero %s; return zero, err }\n", publicName)
	fmt.Fprintf(&r.out, "\treturn lift%s(wire), nil\n}\n\n", publicName)
}

