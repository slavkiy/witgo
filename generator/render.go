func (r *renderer) renderInterface(name string, items []ir.InterfaceItem) error {
	var functions []*ir.Func
	for _, item := range items {
		if fn, ok := item.(*ir.Func); ok {
			functions = append(functions, fn)
		}
	}
	if len(functions) == 0 {
		return nil
	}
	if !r.markEmitted(name, "interface") {
		return nil
	}
	interfaceName := goName(name)
	fmt.Fprintf(&r.out, "type %s interface {\n", interfaceName)
	for _, fn := range functions {
		fmt.Fprintf(&r.out, "\t%s%s\n", goName(fn.Name), r.clientSignature(fn))
	}
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	r.renderInterfaceProvider(name, interfaceName, functions)
	return nil
}

func (r *renderer) renderInterfaceProvider(witName, interfaceName string, functions []*ir.Func) {
	descriptorName := interfaceName + "Descriptor"
	clientName := interfaceName + "ProviderClient"
	for _, generated := range []string{descriptorName, clientName, "Register" + interfaceName, "Resolve" + interfaceName, "AutoResolve" + interfaceName, "MustResolve" + interfaceName} {
		r.reserveGenerated(generated, "composition API for "+strconv.Quote(witName))
	}
	interfaceID := r.interfaceID(witName)
	fmt.Fprintf(&r.out, "var %s = witgo.InterfaceDescriptor{\n", descriptorName)
	fmt.Fprintf(&r.out, "\tID: %s,\n", strconv.Quote(interfaceID))
	fmt.Fprintln(&r.out, "\tFunctions: map[string]string{")
	for _, fn := range functions {
		fmt.Fprintf(&r.out, "\t\t%s: %s,\n", strconv.Quote(fn.Name), strconv.Quote(r.contractTypeSignature(fn)))
	}
	fmt.Fprintln(&r.out, "\t},")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)

	fmt.Fprintf(&r.out, "type %s struct { handle *witgo.ProviderHandle }\n\n", clientName)
	fmt.Fprintf(&r.out, "var _ %s = (*%s)(nil)\n\n", interfaceName, clientName)
	fmt.Fprintf(&r.out, "func (c *%s) witgoCompositionPlug() (witgo.CompositionPlug, bool) {\n", clientName)
	fmt.Fprintln(&r.out, "\tif c == nil || c.handle == nil { return witgo.CompositionPlug{}, false }")
	fmt.Fprintln(&r.out, "\treturn c.handle.CompositionPlug()")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func (c *%s) witgoComponentComposition() witgo.ComponentComposition {\n", clientName)
	fmt.Fprintln(&r.out, "\tplug, ok := c.witgoCompositionPlug()")
	fmt.Fprintln(&r.out, "\tif !ok { return witgo.ComponentComposition{} }")
	fmt.Fprintln(&r.out, "\treturn witgo.ComponentComposition{Component: plug.Component, Dependencies: plug.Dependencies}")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func Register%s(host *witgo.Host, name string, provider %s, options ...witgo.RegisterOption) error {\n", interfaceName, interfaceName)
	fmt.Fprintln(&r.out, "\tif host == nil { return fmt.Errorf(\"host is nil\") }")
	fmt.Fprintln(&r.out, "\tif provider == nil { return fmt.Errorf(\"provider is nil\") }")
	fmt.Fprintln(&r.out, "\tif source, ok := provider.(interface{ witgoComponentComposition() witgo.ComponentComposition }); ok {")
	fmt.Fprintln(&r.out, "\t\tcomposition := source.witgoComponentComposition()")
	fmt.Fprintf(&r.out, "\t\tif composition.Component == \"\" && witgo.DescriptorUsesRuntimeHandles(%s) { return witgo.ErrCrossRuntimeHandle }\n", descriptorName)
	fmt.Fprintln(&r.out, "\t\tif composition.Component != \"\" { options = append(options, witgo.ComponentProvider(composition)) }")
	fmt.Fprintln(&r.out, "\t}")
	fmt.Fprintln(&r.out, "\tif health, ok := provider.(interface{ witgoProviderHealth() error }); ok { if err := health.witgoProviderHealth(); err != nil { return err } }")
	fmt.Fprintf(&r.out, "\t_, err := host.RegisterProvider(name, %s, func(ctx context.Context, function string, args []any) (any, error) {\n", descriptorName)
	fmt.Fprintln(&r.out, "\t\tif health, ok := provider.(interface{ witgoProviderHealth() error }); ok { if err := health.witgoProviderHealth(); err != nil { return nil, err } }")
	fmt.Fprintln(&r.out, "\t\tswitch function {")
	for _, fn := range functions {
		fmt.Fprintf(&r.out, "\t\tcase %s:\n", strconv.Quote(fn.Name))
		fmt.Fprintf(&r.out, "\t\t\tif len(args) != %d { return nil, fmt.Errorf(%q, len(args)) }\n", len(fn.Params), "provider "+interfaceID+"#"+fn.Name+" received %d arguments")
		callArgs := []string{"ctx"}
		for index, param := range fn.Params {
			arg := fmt.Sprintf("_witgoArg%d", index)
			fmt.Fprintf(&r.out, "\t\t\t%s, err := %s\n", arg, r.liftRuntimeExpr("nil", fmt.Sprintf("args[%d]", index), param.Type))
			fmt.Fprintln(&r.out, "\t\t\tif err != nil { return nil, err }")
			callArgs = append(callArgs, arg)
		}
		call := "provider." + goName(fn.Name) + "(" + strings.Join(callArgs, ", ") + ")"
		if _, _, mapped := r.resultErrorParts(fn); mapped {
			r.renderResultErrorProvider("\t\t\t", call, fn)
		} else if fn.Result == nil {
			fmt.Fprintf(&r.out, "\t\t\treturn nil, %s\n", call)
		} else if conversion, ok := r.conversionName(fn.Result); ok {
			fmt.Fprintf(&r.out, "\t\t\t_witgoResult, err := %s\n", call)
			fmt.Fprintln(&r.out, "\t\t\tif err != nil { return nil, err }")
			fmt.Fprintf(&r.out, "\t\t\treturn lower%s(_witgoResult), nil\n", conversion)
		} else {
			fmt.Fprintf(&r.out, "\t\t\treturn %s\n", call)
		}
	}
	fmt.Fprintln(&r.out, "\t\tdefault:")
	fmt.Fprintf(&r.out, "\t\t\treturn nil, fmt.Errorf(%q, function)\n", "unknown provider function "+interfaceID+"#%s")
	fmt.Fprintln(&r.out, "\t\t}")
	fmt.Fprintln(&r.out, "\t}, options...)")
	fmt.Fprintln(&r.out, "\treturn err")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)

	fmt.Fprintf(&r.out, "func Resolve%s(host *witgo.Host, name string) (%s, error) {\n", interfaceName, interfaceName)
	fmt.Fprintln(&r.out, "\tif host == nil { return nil, fmt.Errorf(\"host is nil\") }")
	fmt.Fprintf(&r.out, "\thandle, err := host.ResolveProvider(name, %s)\n", descriptorName)
	fmt.Fprintln(&r.out, "\tif err != nil { return nil, err }")
	fmt.Fprintf(&r.out, "\treturn &%s{handle: handle}, nil\n", clientName)
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func AutoResolve%s(host *witgo.Host) (%s, error) {\n", interfaceName, interfaceName)
	fmt.Fprintln(&r.out, "\tif host == nil { return nil, fmt.Errorf(\"host is nil\") }")
	fmt.Fprintf(&r.out, "\thandle, err := host.AutoResolveProvider(%s)\n", descriptorName)
	fmt.Fprintln(&r.out, "\tif err != nil { return nil, err }")
	fmt.Fprintf(&r.out, "\treturn &%s{handle: handle}, nil\n", clientName)
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func MustResolve%s(host *witgo.Host, name string) %s {\n", interfaceName, interfaceName)
	fmt.Fprintf(&r.out, "\tprovider, err := Resolve%s(host, name)\n", interfaceName)
	fmt.Fprintln(&r.out, "\tif err != nil { panic(err) }")
	fmt.Fprintln(&r.out, "\treturn provider")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)

	for _, fn := range functions {
		fmt.Fprintf(&r.out, "func (c *%s) %s%s {\n", clientName, goName(fn.Name), r.clientSignature(fn))
		args := make([]string, 0, len(fn.Params))
		for index, param := range fn.Params {
			args = append(args, r.lowerExpr(paramName(param, index), param.Type))
		}
		if fn.Result == nil {
			fmt.Fprintf(&r.out, "\t_, _witgoErr := c.handle.CallContext(ctx, %q, %q", "", fn.Name)
			for _, arg := range args {
				fmt.Fprintf(&r.out, ", %s", arg)
			}
			fmt.Fprintln(&r.out, ")")
			fmt.Fprintln(&r.out, "\treturn _witgoErr")
		} else {
			fmt.Fprintf(&r.out, "\t_witgoValue, _witgoErr := c.handle.CallContext(ctx, %q, %q", "", fn.Name)
			for _, arg := range args {
				fmt.Fprintf(&r.out, ", %s", arg)
			}
			fmt.Fprintln(&r.out, ")")
			if _, _, mapped := r.resultErrorParts(fn); mapped {
				r.renderResultErrorClient("\t", "_witgoValue", fn)
			} else {
				fmt.Fprintf(&r.out, "\tif _witgoErr != nil { return %s, _witgoErr }\n", r.zeroValue(fn.Result))
				fmt.Fprintf(&r.out, "\t_witgoResult, _witgoErr := %s\n", r.liftRuntimeExpr("nil", "_witgoValue", fn.Result))
				fmt.Fprintf(&r.out, "\tif _witgoErr != nil { return %s, _witgoErr }\n", r.zeroValue(fn.Result))
				fmt.Fprintln(&r.out, "\treturn _witgoResult, nil")
			}
		}
		fmt.Fprintln(&r.out, "}")
		fmt.Fprintln(&r.out)
	}
}

