package generator

import (
	"bytes"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/slavkiy/witgo/parser/ir"
)

type renderer struct {
	out              bytes.Buffer
	interfaces       map[string]*ir.Interface
	records          map[string]*ir.Record
	namedTypes       map[string]any
	modelFuncs       map[string][]*ir.Func
	exports          map[string]bool
	emitted          map[string]string
	needsFmt         bool
	needsJSON        bool
	needsWitgo       bool
	needsContext     bool
	needsErrors      bool
	hasWorld         bool
	err              error
	witPackage       *ir.Package
	enableRuntimeAPI bool
	goOverlay        *GoOverlay
	goImports        map[string]bool
}

type RenderOptions struct {
	EnableRuntimeAPI bool
	GoOverlay        *GoOverlay
}

// Render converts a lowered WIT file into unformatted Go source.
func Render(file *ir.File, packageName string) ([]byte, error) {
	return RenderWithOptions(file, packageName, RenderOptions{})
}

func RenderWithOptions(file *ir.File, packageName string, options RenderOptions) ([]byte, error) {
	if file == nil {
		return nil, fmt.Errorf("IR file is nil")
	}
	if !isPackageName(packageName) {
		return nil, fmt.Errorf("invalid Go package name %q", packageName)
	}

	r := &renderer{
		interfaces:       make(map[string]*ir.Interface),
		records:          make(map[string]*ir.Record),
		namedTypes:       make(map[string]any),
		modelFuncs:       make(map[string][]*ir.Func),
		exports:          make(map[string]bool),
		emitted:          make(map[string]string),
		witPackage:       file.Package,
		enableRuntimeAPI: options.EnableRuntimeAPI,
		goOverlay:        options.GoOverlay,
		goImports:        make(map[string]bool),
	}
	if options.GoOverlay != nil {
		r.needsFmt = true
		r.needsJSON = true
		for _, mapping := range options.GoOverlay.types {
			if mapping.Config.Import != "" {
				r.goImports[mapping.Config.Import] = true
			}
		}
	}
	r.collect(file)
	if r.err != nil {
		return nil, r.err
	}

	var body bytes.Buffer
	r.out = body
	if err := r.renderFile(file); err != nil {
		return nil, err
	}
	if r.err != nil {
		return nil, r.err
	}
	body = r.out

	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by witgo. DO NOT EDIT.")
	fmt.Fprintln(&out)
	fmt.Fprintf(&out, "package %s\n", packageName)
	if r.needsFmt || r.hasWorld || r.needsJSON || r.needsWitgo || r.needsContext || r.needsErrors || len(r.goImports) > 0 {
		fmt.Fprintln(&out)
		fmt.Fprintln(&out, "import (")
		if r.hasWorld || r.needsContext {
			fmt.Fprintln(&out, `	"context"`)
		}
		if r.hasWorld || r.needsJSON {
			fmt.Fprintln(&out, `	"encoding/json"`)
		}
		if r.needsErrors {
			fmt.Fprintln(&out, `	"errors"`)
		}
		if r.needsFmt || r.hasWorld {
			fmt.Fprintln(&out, `	"fmt"`)
		}
		if r.hasWorld || r.needsWitgo {
			fmt.Fprintln(&out, `	"github.com/slavkiy/witgo"`)
		}
		imports := make([]string, 0, len(r.goImports))
		for importPath := range r.goImports {
			imports = append(imports, importPath)
		}
		sort.Strings(imports)
		for _, importPath := range imports {
			fmt.Fprintf(&out, "\t%q\n", importPath)
		}
		fmt.Fprintln(&out, ")")
	}
	fmt.Fprintln(&out)
	if file.Package != nil {
		fmt.Fprintln(&out, "const (")
		fmt.Fprintf(&out, "\tWITPackageNamespace = %s\n", strconv.Quote(file.Package.Namespace))
		fmt.Fprintf(&out, "\tWITPackageName = %s\n", strconv.Quote(file.Package.Name))
		fmt.Fprintf(&out, "\tWITPackageVersion = %s\n", strconv.Quote(file.Package.Version))
		fmt.Fprintf(&out, "\tWITPackageID = %s\n", strconv.Quote(witPackageID(file.Package)))
		fmt.Fprintln(&out, ")")
		fmt.Fprintln(&out)
	}
	if r.enableRuntimeAPI {
		r.renderRuntimeSystemFacade(&out)
	}
	if r.needsFmt {
		fmt.Fprintln(&out, "func liftValue[T any](value any) (T, error) {")
		fmt.Fprintln(&out, "\tif typed, ok := value.(T); ok {")
		fmt.Fprintln(&out, "\t\treturn typed, nil")
		fmt.Fprintln(&out, "\t}")
		fmt.Fprintln(&out, "\tdata, err := json.Marshal(value)")
		fmt.Fprintln(&out, "\tif err != nil { var zero T; return zero, fmt.Errorf(\"encode component value: %w\", err) }")
		fmt.Fprintln(&out, "\tvar result T")
		fmt.Fprintln(&out, "\tif err := json.Unmarshal(data, &result); err != nil {")
		fmt.Fprintln(&out, "\t\treturn result, fmt.Errorf(\"decode component value: %w\", err)")
		fmt.Fprintln(&out, "\t}")
		fmt.Fprintln(&out, "\treturn result, nil")
		fmt.Fprintln(&out, "}")
		fmt.Fprintln(&out)
	}
	out.Write(body.Bytes())
	return out.Bytes(), nil
}

func (r *renderer) collect(file *ir.File) {
	for _, decl := range file.Decls {
		r.collectNamedDecl(decl)
		switch decl := decl.(type) {
		case *ir.Interface:
			r.interfaces[decl.Name] = decl
			for _, item := range decl.Items {
				r.collectNamedDecl(item)
				if record, ok := item.(*ir.Record); ok {
					r.records[record.Name] = record
				}
				r.inspectItem(item)
			}
		case *ir.Record:
			r.records[decl.Name] = decl
		case *ir.World:
			r.needsFmt = true
			r.hasWorld = true
			for _, item := range decl.Items {
				r.collectNamedDecl(item)
				r.inspectWorldItem(item)
				if export, ok := item.(*ir.Export); ok {
					if path, ok := export.Extern.(*ir.ExternPath); ok && len(path.Path.Segments) > 0 {
						r.exports[path.Path.Segments[len(path.Path.Segments)-1]] = true
					}
				}
			}
		case *ir.TypeDef:
			r.inspectType(decl.Type)
		}
	}
	for name, iface := range r.interfaces {
		if !r.exports[name] {
			continue
		}
		for _, fn := range interfaceFunctions(iface.Items) {
			if len(fn.Params) == 0 {
				continue
			}
			named, ok := fn.Params[0].Type.(*ir.NamedType)
			if ok && r.records[named.Name] != nil {
				r.modelFuncs[named.Name] = append(r.modelFuncs[named.Name], fn)
				r.needsFmt = true
			}
		}
	}
}

func (r *renderer) collectNamedDecl(decl any) {
	switch decl := decl.(type) {
	case *ir.TypeDef:
		r.namedTypes[decl.Name] = decl
	case *ir.Record:
		r.namedTypes[decl.Name] = decl
	case *ir.Flags:
		r.namedTypes[decl.Name] = decl
		r.needsJSON = true
		r.needsFmt = true
		if len(decl.Flags) > 64 && r.err == nil {
			r.err = fmt.Errorf("flags %q has %d members; maximum generated bitset size is 64", decl.Name, len(decl.Flags))
		}
	case *ir.Enum:
		r.namedTypes[decl.Name] = decl
		r.needsJSON = true
		r.needsFmt = true
	case *ir.Variant:
		r.namedTypes[decl.Name] = decl
		r.needsJSON = true
		r.needsFmt = true
	case *ir.Resource:
		r.namedTypes[decl.Name] = decl
		r.needsWitgo = true
	}
}

func (r *renderer) inspectItem(item ir.InterfaceItem) {
	switch item := item.(type) {
	case *ir.TypeDef:
		r.inspectType(item.Type)
	case *ir.Record:
		for _, field := range item.Fields {
			r.inspectType(field.Type)
		}
	case *ir.Variant:
		for _, variantCase := range item.Cases {
			r.inspectType(variantCase.Type)
		}
	case *ir.Func:
		for _, param := range item.Params {
			r.inspectType(param.Type)
		}
		r.inspectType(item.Result)
	}
}

func (r *renderer) inspectWorldItem(item ir.WorldItem) {
	switch item := item.(type) {
	case *ir.Func:
		r.inspectType(item.Result)
	case *ir.Import:
		r.inspectExtern(item.Extern)
	case *ir.Export:
		r.inspectExtern(item.Extern)
	}
}

func (r *renderer) inspectExtern(extern ir.ExternType) {
	switch extern := extern.(type) {
	case *ir.InlineInterface:
		for _, item := range extern.Items {
			r.inspectItem(item)
		}
	case *ir.FuncType:
		r.inspectType(extern.Func.Result)
	}
}

func (r *renderer) inspectType(typ ir.Type) {
	switch typ := typ.(type) {
	case *ir.PrimitiveType:
		if typ.Name == "char" {
			r.needsWitgo = true
		}
	case *ir.NamedType:
		if typ.Name == "error-context" || typ.Name == "char" {
			r.needsWitgo = true
		}
	case *ir.GenericType:
		if typ.Name == "result" || typ.Name == "option" {
			r.needsWitgo = true
		}
		if typ.Name == "borrow" || typ.Name == "own" || typ.Name == "future" || typ.Name == "stream" {
			r.needsWitgo = true
		}
		for _, arg := range typ.Args {
			r.inspectType(arg)
		}
	case *ir.TupleType:
		r.needsWitgo = true
		for _, item := range typ.Items {
			r.inspectType(item)
		}
	}
}

func (r *renderer) renderFile(file *ir.File) error {
	for _, decl := range file.Decls {
		switch decl := decl.(type) {
		case *ir.Interface:
			if err := r.renderInterfaceTypes(decl); err != nil {
				return err
			}
		case *ir.World:
			if err := r.renderWorldTypes(decl); err != nil {
				return err
			}
		default:
			if err := r.renderTypeDecl(decl); err != nil {
				return err
			}
		}
	}

	for _, decl := range file.Decls {
		if iface, ok := decl.(*ir.Interface); ok {
			if err := r.renderInterface(iface.Name, iface.Items); err != nil {
				return err
			}
		}
	}

	worldCount := 0
	for _, decl := range file.Decls {
		if _, ok := decl.(*ir.World); ok {
			worldCount++
		}
	}
	if worldCount > 0 {
		fmt.Fprintln(&r.out, "type runtimeCaller interface {")
		fmt.Fprintln(&r.out, "\tCallContext(ctx context.Context, name string, args ...any) (any, error)")
		fmt.Fprintln(&r.out, "\tClose() error")
		fmt.Fprintln(&r.out, "}")
		fmt.Fprintln(&r.out)
	}
	for _, decl := range file.Decls {
		if world, ok := decl.(*ir.World); ok {
			if err := r.renderWorld(world); err != nil {
				return err
			}
		}
	}
	return nil
}

func (r *renderer) renderRuntimeSystemFacade(out *bytes.Buffer) {
	fmt.Fprintln(out, "// RuntimeSystem - vendor capability witgo:runtime/runtime@1.0.0.")
	fmt.Fprintln(out, "// Read-only methods expose only call-local sanitized state.")
	fmt.Fprintln(out, "type RuntimeSystem interface {")
	fmt.Fprintln(out, "\tCallInfo() (witgo.RuntimeCallInfo, error)")
	fmt.Fprintln(out, "\tFuelInfo() (witgo.RuntimeFuelInfo, error)")
	fmt.Fprintln(out, "\tLimits() (witgo.RuntimeLimits, error)")
	fmt.Fprintln(out, "\tIsCancelled() (bool, error)")
	fmt.Fprintln(out, "\t// UnsafeRequestAdditionalFuel asks host policy for a bounded grant; denial is normal.")
	fmt.Fprintln(out, "\tUnsafeRequestAdditionalFuel(amount uint64, reason string) (witgo.FuelGrant, error)")
	fmt.Fprintln(out, "}")
	fmt.Fprintln(out)
	fmt.Fprintln(out, "// System groups opt-in system capabilities available to guest plugin code.")
	fmt.Fprintln(out, "type System struct { Runtime RuntimeSystem }")
	fmt.Fprintln(out)
}

func (r *renderer) renderInterfaceTypes(iface *ir.Interface) error {
	for _, item := range iface.Items {
		if _, ok := item.(*ir.Use); ok {
			continue
		}
		if _, ok := item.(*ir.Func); ok {
			continue
		}
		if err := r.renderTypeDecl(item); err != nil {
			return fmt.Errorf("interface %q: %w", iface.Name, err)
		}
	}
	return nil
}

func (r *renderer) renderWorldTypes(world *ir.World) error {
	for _, item := range world.Items {
		switch item := item.(type) {
		case *ir.Use, *ir.Func, *ir.Import, *ir.Export, *ir.Include:
			continue
		default:
			if err := r.renderTypeDecl(item); err != nil {
				return fmt.Errorf("world %q: %w", world.Name, err)
			}
		}
	}
	return nil
}

func (r *renderer) renderTypeDecl(decl any) error {
	switch decl := decl.(type) {
	case *ir.TypeDef:
		if !r.markEmitted(decl.Name, "type") {
			return nil
		}
		if mapping, ok := r.typeMapping(decl.Name); ok {
			fmt.Fprintf(&r.out, "type %s = %s\n\n", goName(decl.Name), mapping.Config.GoType)
			r.renderMappedAliasCodec(decl, mapping)
		} else {
			fmt.Fprintf(&r.out, "type %s = %s\n\n", goName(decl.Name), r.goType(decl.Type))
		}
	case *ir.Record:
		if !r.markEmitted(decl.Name, "record") {
			return nil
		}
		r.renderRecord(decl)
	case *ir.Flags:
		if !r.markEmitted(decl.Name, "flags") {
			return nil
		}
		r.renderFlags(decl)
	case *ir.Enum:
		if !r.markEmitted(decl.Name, "enum") {
			return nil
		}
		r.renderEnum(decl)
	case *ir.Variant:
		if !r.markEmitted(decl.Name, "variant") {
			return nil
		}
		r.renderVariant(decl)
	case *ir.Resource:
		if !r.markEmitted(decl.Name, "resource") {
			return nil
		}
		r.renderResource(decl)
	case *ir.Interface, *ir.World:
		return nil
	default:
		return fmt.Errorf("unsupported declaration %T", decl)
	}
	return nil
}

func (r *renderer) markEmitted(name, kind string) bool {
	goIdentifier := goName(name)
	if previous, exists := r.emitted[goIdentifier]; exists {
		if r.err == nil {
			r.err = fmt.Errorf("Go name collision: WIT %s %q and %s both generate %q", previous, name, kind, goIdentifier)
		}
		return false
	}
	r.emitted[goIdentifier] = kind + " " + strconv.Quote(name)
	return true
}

func (r *renderer) reserveGenerated(name, origin string) {
	if previous, exists := r.emitted[name]; exists {
		if r.err == nil {
			r.err = fmt.Errorf("Go name collision: %s and generated %s both use %q", previous, origin, name)
		}
		return
	}
	r.emitted[name] = "generated " + origin
}

func (r *renderer) renderRecord(record *ir.Record) {
	name := goName(record.Name)
	fmt.Fprintf(&r.out, "type %s struct {\n", name)
	for _, field := range record.Fields {
		fmt.Fprintf(&r.out, "\t%s %s `json:%s`\n", goName(field.Name), r.goType(field.Type), strconv.Quote(field.Name))
	}
	if len(r.modelFuncs[record.Name]) > 0 {
		fmt.Fprintf(&r.out, "\tbinding %sBinding\n", goLocalName(record.Name))
	}
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	if r.recordHasOverlay(record) {
		r.renderRecordCodec(record)
	}

	if functions := r.modelFuncs[record.Name]; len(functions) > 0 {
		fmt.Fprintf(&r.out, "type %sBinding interface {\n", goLocalName(record.Name))
		for _, fn := range functions {
			fmt.Fprintf(&r.out, "\t%s%s\n", goName(fn.Name), r.clientSignature(fn))
		}
		fmt.Fprintln(&r.out, "}")
		fmt.Fprintln(&r.out)
		for _, fn := range functions {
			fmt.Fprintf(&r.out, "func (value %s) %s%s {\n", name, modelMethodName(record.Name, fn.Name), r.modelSignature(fn))
			fmt.Fprintln(&r.out, "\tif value.binding == nil {")
			if okType, _, mapped := r.resultErrorParts(fn); mapped && isUnitType(okType) {
				fmt.Fprintln(&r.out, `		return fmt.Errorf("model is not attached to a plugin")`)
			} else if okType, _, mapped := r.resultErrorParts(fn); mapped {
				fmt.Fprintf(&r.out, "\t\treturn %s, fmt.Errorf(%q)\n", r.zeroValue(okType), "model is not attached to a plugin")
			} else if fn.Result == nil {
				fmt.Fprintln(&r.out, `		return fmt.Errorf("model is not attached to a plugin")`)
			} else {
				fmt.Fprintf(&r.out, "\t\treturn %s, fmt.Errorf(%q)\n", r.zeroValue(fn.Result), "model is not attached to a plugin")
			}
			fmt.Fprintln(&r.out, "\t}")
			args := []string{"ctx", "value"}
			for index, param := range fn.Params[1:] {
				args = append(args, paramName(param, index+1))
			}
			fmt.Fprintf(&r.out, "\treturn value.binding.%s(%s)\n", goName(fn.Name), strings.Join(args, ", "))
			fmt.Fprintln(&r.out, "}")
			fmt.Fprintln(&r.out)
		}
	}

}

func (r *renderer) renderFlags(flags *ir.Flags) {
	name := goName(flags.Name)
	local := goLocalName(flags.Name)
	r.reserveGenerated("Parse"+name, "flags parser for "+strconv.Quote(flags.Name))
	fmt.Fprintf(&r.out, "type %s uint64\n\n", name)
	fmt.Fprintln(&r.out, "const (")
	for index, flag := range flags.Flags {
		fmt.Fprintf(&r.out, "\t%s%s %s = 1 << %d\n", name, goName(flag), name, index)
	}
	fmt.Fprintln(&r.out, ")")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "const %sKnown %s = ", local, name)
	if len(flags.Flags) == 0 {
		fmt.Fprintln(&r.out, "0")
	} else {
		parts := make([]string, 0, len(flags.Flags))
		for _, flag := range flags.Flags {
			parts = append(parts, name+goName(flag))
		}
		fmt.Fprintln(&r.out, strings.Join(parts, " | "))
	}
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func (value %s) Valid() bool { return value &^ %sKnown == 0 }\n", name, local)
	fmt.Fprintf(&r.out, "func (value %s) Has(flags %s) bool { return flags != 0 && flags.Valid() && value&flags == flags }\n", name, name)
	fmt.Fprintf(&r.out, "func (value *%s) Add(flags ...%s) { for _, flag := range flags { *value |= flag } }\n", name, name)
	fmt.Fprintf(&r.out, "func (value *%s) Remove(flags ...%s) { for _, flag := range flags { *value &^= flag } }\n", name, name)
	fmt.Fprintf(&r.out, "func (value %s) Names() ([]string, error) {\n", name)
	fmt.Fprintf(&r.out, "\tif !value.Valid() { return nil, fmt.Errorf(%q, value &^ %sKnown) }\n", "flags contain unknown bits: %d", local)
	fmt.Fprintln(&r.out, "\tnames := make([]string, 0)")
	for _, flag := range flags.Flags {
		fmt.Fprintf(&r.out, "\tif value&%s%s != 0 { names = append(names, %s) }\n", name, goName(flag), strconv.Quote(flag))
	}
	fmt.Fprintln(&r.out, "\treturn names, nil")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func Parse%s(names ...string) (%s, error) {\n", name, name)
	fmt.Fprintf(&r.out, "\tvar result %s\n", name)
	fmt.Fprintln(&r.out, "\tfor _, flag := range names { switch flag {")
	for _, flag := range flags.Flags {
		fmt.Fprintf(&r.out, "\tcase %s: result |= %s%s\n", strconv.Quote(flag), name, goName(flag))
	}
	fmt.Fprintf(&r.out, "%s\n", "\tdefault: return 0, fmt.Errorf(\"unknown flag %q\", flag)")
	fmt.Fprintln(&r.out, "\t} }")
	fmt.Fprintln(&r.out, "\treturn result, nil")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func (value %s) MarshalJSON() ([]byte, error) {\n", name)
	fmt.Fprintln(&r.out, "\tnames, err := value.Names()")
	fmt.Fprintln(&r.out, "\tif err != nil { return nil, err }")
	fmt.Fprintln(&r.out, "\treturn json.Marshal(names)")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func (value *%s) UnmarshalJSON(data []byte) error {\n", name)
	fmt.Fprintln(&r.out, "\tif value == nil { return fmt.Errorf(\"cannot decode flags into nil receiver\") }")
	fmt.Fprintln(&r.out, "\tvar names []string")
	fmt.Fprintln(&r.out, "\tif err := json.Unmarshal(data, &names); err != nil { return err }")
	fmt.Fprintf(&r.out, "\tresult, err := Parse%s(names...)\n", name)
	fmt.Fprintln(&r.out, "\tif err != nil { return err }")
	fmt.Fprintln(&r.out, "\t*value = result")
	fmt.Fprintln(&r.out, "\treturn nil")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
}

func (r *renderer) renderEnum(enum *ir.Enum) {
	name := goName(enum.Name)
	r.reserveGenerated("Parse"+name, "enum parser for "+strconv.Quote(enum.Name))
	r.reserveGenerated(name+"Values", "enum values helper for "+strconv.Quote(enum.Name))
	fmt.Fprintf(&r.out, "type %s string\n\n", name)
	fmt.Fprintln(&r.out, "const (")
	for _, enumCase := range enum.Cases {
		fmt.Fprintf(&r.out, "\t%s%s %s = %s\n", name, goName(enumCase), name, strconv.Quote(enumCase))
	}
	fmt.Fprintln(&r.out, ")")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "func (value %s) String() string { return string(value) }\n", name)
	fmt.Fprintf(&r.out, "func (value %s) Valid() bool {\n\tswitch value {\n", name)
	if len(enum.Cases) > 0 {
		cases := make([]string, 0, len(enum.Cases))
		for _, enumCase := range enum.Cases {
			cases = append(cases, name+goName(enumCase))
		}
		fmt.Fprintf(&r.out, "\tcase %s: return true\n", strings.Join(cases, ", "))
	}
	fmt.Fprintln(&r.out, "\tdefault: return false\n\t}\n}")
	fmt.Fprintf(&r.out, "func Parse%s(value string) (%s, error) {\n", name, name)
	fmt.Fprintf(&r.out, "\tresult := %s(value)\n", name)
	fmt.Fprintf(&r.out, "\tif !result.Valid() { return \"\", fmt.Errorf(%q, value) }\n", "unknown "+enum.Name+" value %q")
	fmt.Fprintln(&r.out, "\treturn result, nil\n}")
	fmt.Fprintf(&r.out, "func %sValues() []%s { return []%s{", name, name, name)
	for index, enumCase := range enum.Cases {
		if index > 0 {
			fmt.Fprint(&r.out, ", ")
		}
		fmt.Fprint(&r.out, name+goName(enumCase))
	}
	fmt.Fprintln(&r.out, "} }")
	fmt.Fprintf(&r.out, "func (value %s) MarshalJSON() ([]byte, error) { if !value.Valid() { return nil, fmt.Errorf(%q, value) }; return json.Marshal(string(value)) }\n", name, "unknown "+enum.Name+" value %q")
	fmt.Fprintf(&r.out, "func (value *%s) UnmarshalJSON(data []byte) error { if value == nil { return fmt.Errorf(\"cannot decode enum into nil receiver\") }; var text string; if err := json.Unmarshal(data, &text); err != nil { return err }; result, err := Parse%s(text); if err != nil { return err }; *value = result; return nil }\n", name, name)
	fmt.Fprintln(&r.out)
}

func (r *renderer) renderVariant(variant *ir.Variant) {
	name := goName(variant.Name)
	for _, variantCase := range variant.Cases {
		r.reserveGenerated("New"+name+goName(variantCase.Name), "variant constructor for "+strconv.Quote(variant.Name+"."+variantCase.Name))
	}
	fmt.Fprintf(&r.out, "type %sKind uint32\n\n", name)
	fmt.Fprintln(&r.out, "const (")
	for index, variantCase := range variant.Cases {
		fmt.Fprintf(&r.out, "\t%sKind%s %sKind = %d\n", name, goName(variantCase.Name), name, index)
	}
	fmt.Fprintln(&r.out, ")")
	fmt.Fprintln(&r.out)
	fmt.Fprintf(&r.out, "type %s struct {\n\tKind %sKind `json:%s`\n", name, name, strconv.Quote("kind"))
	for _, variantCase := range variant.Cases {
		if variantCase.Type != nil {
			fmt.Fprintf(&r.out, "\t%s *%s `json:%s`\n", goName(variantCase.Name), r.goType(variantCase.Type), strconv.Quote(variantCase.Name+",omitempty"))
		}
	}
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
	for _, variantCase := range variant.Cases {
		caseName := goName(variantCase.Name)
		if variantCase.Type == nil {
			fmt.Fprintf(&r.out, "func New%s%s() %s { return %s{Kind: %sKind%s} }\n", name, caseName, name, name, name, caseName)
		} else {
			fmt.Fprintf(&r.out, "func New%s%s(payload %s) %s { return %s{Kind: %sKind%s, %s: &payload} }\n", name, caseName, r.goType(variantCase.Type), name, name, name, caseName, caseName)
			fmt.Fprintf(&r.out, "func (value %s) Get%s() (%s, bool) { if value.Kind != %sKind%s || value.%s == nil { var zero %s; return zero, false }; return *value.%s, true }\n", name, caseName, r.goType(variantCase.Type), name, caseName, caseName, r.goType(variantCase.Type), caseName)
		}
		fmt.Fprintf(&r.out, "func (value %s) Is%s() bool { return value.Kind == %sKind%s }\n", name, caseName, name, caseName)
	}
	fmt.Fprintln(&r.out)

	fmt.Fprintf(&r.out, "func (value %s) MarshalJSON() ([]byte, error) {\n", name)
	fmt.Fprintln(&r.out, "\tswitch value.Kind {")
	for _, variantCase := range variant.Cases {
		fmt.Fprintf(&r.out, "\tcase %sKind%s:\n", name, goName(variantCase.Name))
		if variantCase.Type == nil {
			fmt.Fprintf(&r.out, "\t\treturn json.Marshal(struct { Case string `json:%s` }{Case: %s})\n", strconv.Quote("case"), strconv.Quote(variantCase.Name))
		} else {
			fmt.Fprintf(&r.out, "\t\tif value.%s == nil { return nil, fmt.Errorf(%q) }\n", goName(variantCase.Name), "variant "+variant.Name+" case "+variantCase.Name+" has nil payload")
			fmt.Fprintf(&r.out, "\t\treturn json.Marshal(struct { Case string `json:%s`; Value any `json:%s` }{Case: %s, Value: *value.%s})\n", strconv.Quote("case"), strconv.Quote("value"), strconv.Quote(variantCase.Name), goName(variantCase.Name))
		}
	}
	fmt.Fprintln(&r.out, "\tdefault:")
	fmt.Fprintf(&r.out, "\t\treturn nil, fmt.Errorf(%q, value.Kind)\n", "variant "+variant.Name+" has invalid kind %d")
	fmt.Fprintln(&r.out, "\t}")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)

	fmt.Fprintf(&r.out, "func (value *%s) UnmarshalJSON(data []byte) error {\n", name)
	fmt.Fprintln(&r.out, "\tif value == nil { return fmt.Errorf(\"cannot decode variant into nil receiver\") }")
	fmt.Fprintln(&r.out, "\tvar envelope struct { Case string `json:\"case\"`; Value json.RawMessage `json:\"value\"` }")
	fmt.Fprintln(&r.out, "\tif err := json.Unmarshal(data, &envelope); err != nil { return err }")
	fmt.Fprintln(&r.out, "\tswitch envelope.Case {")
	for _, variantCase := range variant.Cases {
		fmt.Fprintf(&r.out, "\tcase %s:\n", strconv.Quote(variantCase.Name))
		fmt.Fprintf(&r.out, "\t\t*value = %s{Kind: %sKind%s}\n", name, name, goName(variantCase.Name))
		if variantCase.Type != nil {
			fmt.Fprintf(&r.out, "\t\tvar payload %s\n", r.goType(variantCase.Type))
			fmt.Fprintln(&r.out, "\t\tif err := json.Unmarshal(envelope.Value, &payload); err != nil { return err }")
			fmt.Fprintf(&r.out, "\t\tvalue.%s = &payload\n", goName(variantCase.Name))
		}
		fmt.Fprintln(&r.out, "\t\treturn nil")
	}
	fmt.Fprintln(&r.out, "\tdefault:")
	fmt.Fprintf(&r.out, "\t\treturn fmt.Errorf(%q, envelope.Case)\n", "variant "+variant.Name+" has unknown case %q")
	fmt.Fprintln(&r.out, "\t}")
	fmt.Fprintln(&r.out, "}")
	fmt.Fprintln(&r.out)
}

