func goPackageName(name string) string {
	var out strings.Builder
	for _, char := range strings.ToLower(name) {
		if unicode.IsLetter(char) || unicode.IsDigit(char) || char == '_' {
			out.WriteRune(char)
		} else {
			out.WriteRune('_')
		}
	}
	result := strings.Trim(out.String(), "_")
	if result == "" || unicode.IsDigit([]rune(result)[0]) || goKeywords[result] {
		return "wit_" + result
	}
	return result
}

func firstType(types []ir.Type) ir.Type {
	if len(types) == 0 {
		return nil
	}
	return types[0]
}

func isPackageName(name string) bool {
	if name == "" {
		return false
	}
	for index, char := range name {
		if index == 0 && !unicode.IsLetter(char) && char != '_' {
			return false
		}
		if index > 0 && !unicode.IsLetter(char) && !unicode.IsDigit(char) && char != '_' {
			return false
		}
	}
	return !goKeywords[name]
}

func goName(name string) string {
	words := strings.FieldsFunc(name, func(char rune) bool {
		return char == '-' || char == '_' || unicode.IsSpace(char)
	})
	for index, word := range words {
		lower := strings.ToLower(word)
		if initialisms[lower] {
			words[index] = strings.ToUpper(lower)
			continue
		}
		runes := []rune(word)
		if len(runes) > 0 {
			runes[0] = unicode.ToUpper(runes[0])
		}
		words[index] = string(runes)
	}
	result := strings.Join(words, "")
	if result == "" {
		return "Value"
	}
	if unicode.IsDigit([]rune(result)[0]) {
		result = "Value" + result
	}
	return result
}

func goLocalName(name string) string {
	exported := goName(name)
	if initialisms[strings.ToLower(exported)] {
		return strings.ToLower(exported)
	}
	runes := []rune(exported)
	runes[0] = unicode.ToLower(runes[0])
	result := string(runes)
	if goKeywords[result] {
		return result + "Value"
	}
	return result
}

var initialisms = map[string]bool{
	"api": true, "http": true, "https": true, "id": true, "ip": true,
	"json": true, "sql": true, "sso": true, "tcp": true, "udp": true,
	"uri": true, "url": true, "uuid": true, "xml": true,
}

var goKeywords = map[string]bool{
	"break": true, "default": true, "func": true, "interface": true,
	"select": true, "case": true, "defer": true, "go": true, "map": true,
	"struct": true, "chan": true, "else": true, "goto": true, "package": true,
	"switch": true, "const": true, "fallthrough": true, "if": true,
	"range": true, "type": true, "continue": true, "for": true,
	"import": true, "return": true, "var": true,
}
